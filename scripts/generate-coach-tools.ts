import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import {
  COACH_CAPABILITY_ORDER,
  COACH_REALTIME_TOOL_NAMES,
  COACH_TOOL_REGISTRY,
} from "../shared/coach/toolRegistry";

const cwd = process.cwd();
const root = cwd.endsWith("/supabase") ? resolve(cwd, "..") : cwd;
const serialized = JSON.stringify(COACH_TOOL_REGISTRY);
const sourceHash = createHash("sha256").update(serialized).digest("hex").slice(0, 16);
const banner = `// Generated by scripts/generate-coach-tools.ts. Do not edit.\n// source-hash: ${sourceHash}\n`;
const registryLiteral = JSON.stringify(COACH_TOOL_REGISTRY, null, 2);
const capabilitiesLiteral = JSON.stringify(COACH_CAPABILITY_ORDER, null, 2);
const realtimeNamesLiteral = JSON.stringify(COACH_REALTIME_TOOL_NAMES, null, 2);

const backend = `${banner}
export const GENERATED_COACH_TOOL_REGISTRY = ${registryLiteral} as const;
export type CoachToolName = typeof GENERATED_COACH_TOOL_REGISTRY[number]["name"];
export type CoachCapability = typeof GENERATED_COACH_TOOL_REGISTRY[number]["capability"];
export const COACH_REALTIME_TOOL_NAMES = ${realtimeNamesLiteral} as readonly string[];
export interface RealtimeFunctionTool {
  type: "function";
  name: string;
  description: string;
  parameters: {
    type: "object";
    properties: Record<string, Record<string, unknown>>;
    required?: readonly string[];
    additionalProperties?: boolean;
  };
}

export const COACH_TOOL_NAMES = new Set<string>(
  GENERATED_COACH_TOOL_REGISTRY.map((tool) => tool.name)
);
export const COACH_SERVER_TOOL_NAMES = new Set<string>(
  GENERATED_COACH_TOOL_REGISTRY.filter((tool) => tool.execution === "server").map((tool) => tool.name)
);
export const COACH_READ_ONLY_TOOLS = new Set<string>(
  GENERATED_COACH_TOOL_REGISTRY
    .filter((tool) => tool.execution === "server" && tool.kind === "read_only")
    .map((tool) => tool.name)
);
export const COACH_IDEMPOTENT_TOOLS = new Set<string>(
  GENERATED_COACH_TOOL_REGISTRY.filter((tool) => tool.kind === "mutation" && tool.execution === "server")
    .map((tool) => tool.name)
);

type ValidationResult =
  | { ok: true; value: Record<string, unknown> }
  | { ok: false; error: string };

export function validateCoachToolArguments(
  toolName: string,
  input: unknown
): ValidationResult {
  const tool = GENERATED_COACH_TOOL_REGISTRY.find((candidate) => candidate.name === toolName);
  if (!tool) return { ok: false, error: "Unsupported coach action." };
  if (!input || typeof input !== "object" || Array.isArray(input)) {
    return { ok: false, error: "Coach action arguments must be an object." };
  }
  const value = input as Record<string, unknown>;
  const properties = tool.parameters.properties as Record<string, Record<string, unknown>>;
  for (const key of Object.keys(value)) {
    if (!(key in properties) && key !== "client_request_id") {
      return { ok: false, error: \`Unexpected coach action field: \${key}.\` };
    }
  }
  for (const required of ("required" in tool.parameters ? tool.parameters.required : []) ?? []) {
    if (value[required] == null) {
      return { ok: false, error: \`Missing required coach action field: \${required}.\` };
    }
  }
  for (const [key, schema] of Object.entries(properties)) {
    const field = value[key];
    if (field == null) continue;
    const expected = schema.type;
    if (expected === "string" && typeof field !== "string") {
      return { ok: false, error: \`\${key} must be text.\` };
    }
    if (expected === "boolean" && typeof field !== "boolean") {
      return { ok: false, error: \`\${key} must be true or false.\` };
    }
    if ((expected === "number" || expected === "integer") && typeof field !== "number") {
      return { ok: false, error: \`\${key} must be a number.\` };
    }
    if (expected === "integer" && !Number.isInteger(field)) {
      return { ok: false, error: \`\${key} must be a whole number.\` };
    }
    if (typeof field === "number") {
      if (typeof schema.minimum === "number" && field < schema.minimum) {
        return { ok: false, error: \`\${key} is below its allowed minimum.\` };
      }
      if (typeof schema.exclusiveMinimum === "number" && field <= schema.exclusiveMinimum) {
        return { ok: false, error: \`\${key} must be greater than \${schema.exclusiveMinimum}.\` };
      }
      if (typeof schema.maximum === "number" && field > schema.maximum) {
        return { ok: false, error: \`\${key} exceeds its allowed maximum.\` };
      }
    }
    if (typeof field === "string") {
      if (
        Array.isArray(schema.enum)
        && !(schema.enum as readonly unknown[]).includes(field)
      ) {
        return { ok: false, error: \`\${key} is not an allowed value.\` };
      }
      if (typeof schema.minLength === "number" && field.length < schema.minLength) {
        return { ok: false, error: \`\${key} is too short.\` };
      }
      if (typeof schema.maxLength === "number" && field.length > schema.maxLength) {
        return { ok: false, error: \`\${key} is too long.\` };
      }
    }
  }
  const makes = value.makes ?? value.target_makes;
  const attempts = value.attempts ?? value.target_attempts;
  if (
    typeof makes === "number"
    && typeof attempts === "number"
    && makes > attempts
  ) {
    return { ok: false, error: "Makes cannot exceed attempts." };
  }
  if (value.minutes != null && value.seconds != null) {
    return { ok: false, error: "Use either minutes or seconds, not both." };
  }
  return { ok: true, value };
}

export function generatedRealtimeTools(
  capabilities?: readonly CoachCapability[]
): RealtimeFunctionTool[] {
  const allowed = capabilities ? new Set(capabilities) : null;
  return GENERATED_COACH_TOOL_REGISTRY
    .filter((tool) =>
      COACH_REALTIME_TOOL_NAMES.includes(tool.name)
      && (!allowed || allowed.has(tool.capability))
    )
    .map((tool) => ({
      type: "function" as const,
      name: tool.name,
      description: tool.description,
      parameters: tool.parameters,
    })) as RealtimeFunctionTool[];
}

export function generatedResponseTools(
  capabilities?: readonly CoachCapability[]
): Array<RealtimeFunctionTool & { strict: false }> {
  const allowed = capabilities ? new Set(capabilities) : null;
  return GENERATED_COACH_TOOL_REGISTRY
    .filter((tool) =>
      tool.execution === "server"
      && tool.realtime
      && (!allowed || allowed.has(tool.capability))
    )
    .map((tool) => ({
      type: "function" as const,
      name: tool.name,
      description: tool.description,
      parameters: tool.parameters,
      // Optional drill references are intentional, so OpenAI strict mode cannot
      // be used without changing the domain contract. Runtime validation below
      // remains authoritative.
      strict: false as const,
    })) as Array<RealtimeFunctionTool & { strict: false }>;
}
`;

const frontend = `${banner}
export const COACH_CAPABILITY_ORDER = ${capabilitiesLiteral} as const;
export type CoachCapability = typeof COACH_CAPABILITY_ORDER[number];
export const COACH_REALTIME_TOOL_NAMES = ${realtimeNamesLiteral} as const;
export const COACH_REALTIME_TOOLS = ${JSON.stringify(
  COACH_TOOL_REGISTRY.filter((tool) =>
    (COACH_REALTIME_TOOL_NAMES as readonly string[]).includes(tool.name)
  ).map((tool) => ({
    type: "function",
    name: tool.name,
    description: tool.description,
    parameters: tool.parameters,
  })),
  null,
  2
)} as const;
export const COACH_TOOL_METADATA = ${JSON.stringify(
  COACH_TOOL_REGISTRY.map((tool) => ({
    name: tool.name,
    capability: tool.capability,
    execution: tool.execution,
    kind: tool.kind,
    realtime: (COACH_REALTIME_TOOL_NAMES as readonly string[]).includes(tool.name),
    flushShots: tool.flushShots ?? false,
    exactSpeech: tool.exactSpeech ?? false,
  })),
  null,
  2
)} as const;
export type CoachToolName = typeof COACH_TOOL_METADATA[number]["name"];
export const COACH_TOOL_BY_NAME = new Map<string, typeof COACH_TOOL_METADATA[number]>(
  COACH_TOOL_METADATA.map((tool) => [tool.name, tool])
);
export function toolNamesForCapabilities(capabilities: readonly CoachCapability[]): string[] {
  const allowed = new Set(capabilities);
  return COACH_TOOL_METADATA
    .filter((tool) => tool.realtime && allowed.has(tool.capability))
    .map((tool) => tool.name);
}
export function realtimeToolsForCapabilities(capabilities?: readonly CoachCapability[]) {
  if (!capabilities) return [...COACH_REALTIME_TOOLS];
  const names = new Set(toolNamesForCapabilities(capabilities));
  return COACH_REALTIME_TOOLS.filter((tool) => names.has(tool.name));
}
`;

async function main() {
  const backendPath = resolve(root, "supabase/functions/_shared/generated/coachTools.ts");
  const frontendPath = resolve(root, "frontend/lib/generated/coachTools.ts");
  if (process.argv.includes("--check")) {
    const [currentBackend, currentFrontend] = await Promise.all([
      readFile(backendPath, "utf8"),
      readFile(frontendPath, "utf8"),
    ]);
    if (currentBackend !== backend || currentFrontend !== frontend) {
      throw new Error("Generated coach tool contracts are stale.");
    }
    console.log(`Coach tool contracts are current (${sourceHash}).`);
    return;
  }
  await mkdir(resolve(root, "supabase/functions/_shared/generated"), { recursive: true });
  await mkdir(resolve(root, "frontend/lib/generated"), { recursive: true });
  await writeFile(backendPath, backend);
  await writeFile(frontendPath, frontend);
  console.log(`Generated coach tool contracts (${sourceHash}).`);
}

void main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
