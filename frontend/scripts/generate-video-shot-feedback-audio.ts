// @ts-nocheck -- Node-only asset generation script; app tsconfig targets React Native.
import { createClient } from "@inworld/tts";
import { mkdir, rename, stat, unlink, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import {
  FLOATER_MAKES,
  FLOATER_MISSES,
  LAYUP_MAKES,
  LAYUP_MISSES,
  SHOOTING_MAKES,
  SHOOTING_MISSES,
} from "../lib/videoShotFeedback";

const ROOT = resolve(import.meta.dirname, "..");
const OUTPUT = resolve(ROOT, "assets/sounds/VideoShotFeedback");
const token = process.env.INWORLD_TOKEN?.trim();
const apiKey = process.env.INWORLD_API_KEY?.trim();
if (!token && !apiKey) throw new Error("Set INWORLD_TOKEN or INWORLD_API_KEY.");

const client = createClient({
  ...(token ? { token } : { apiKey }),
  timeout: 60_000,
  maxRetries: 3,
  maxConcurrentRequests: 4,
});
const voices = { devin: "Nate", tyler: "Evan", maya: "Sarah", ava: "Zadie" } as const;
const groups = {
  "shooting-make": SHOOTING_MAKES,
  "layup-make": LAYUP_MAKES,
  "floater-make": FLOATER_MAKES,
  "shooting-miss": SHOOTING_MISSES,
  "layup-miss": LAYUP_MISSES,
  "floater-miss": FLOATER_MISSES,
  streak: [
    "Keep going, you're 3 in a row.",
    "Keep going, you're 5 in a row.",
    "Keep going, you're 10 in a row.",
  ],
} as const;
const jobs = Object.entries(voices).flatMap(([persona, voice]) =>
  Object.entries(groups).flatMap(([group, texts]) =>
    texts.map((text, index) => ({
      persona,
      voice,
      text,
      path: resolve(OUTPUT, persona, group, `${String(index + 1).padStart(2, "0")}.mp3`),
    }))
  )
);

async function exists(path: string) {
  try { return (await stat(path)).size > 256; } catch { return false; }
}

let cursor = 0;
async function worker() {
  while (cursor < jobs.length) {
    const job = jobs[cursor++];
    if (await exists(job.path)) continue;
    const temporary = `${job.path}.part`;
    await mkdir(dirname(job.path), { recursive: true });
    await unlink(temporary).catch(() => undefined);
    const audio = await client.generate({
      text: `[warm supportive basketball coach, concise and energetic] ${job.text}`,
      voice: job.voice,
      model: "inworld-tts-2",
      encoding: "MP3",
      sampleRate: 16_000,
      bitRate: 64_000,
      language: "en-US",
      speakingRate: 1.08,
      deliveryMode: "BALANCED",
    });
    await writeFile(temporary, audio);
    await rename(temporary, job.path);
    console.log(`${cursor}/${jobs.length} ${job.persona}/${job.text}`);
  }
}

async function main() {
await Promise.all(Array.from({ length: 4 }, worker));
const lines = [
  "/* Generated by scripts/generate-video-shot-feedback-audio.ts. */",
  "/* eslint-disable @typescript-eslint/no-require-imports */",
  'export type VideoFeedbackPersona = "devin" | "tyler" | "maya" | "ava";',
  "export const VIDEO_SHOT_FEEDBACK_AUDIO: Record<VideoFeedbackPersona, Record<string, number>> = {",
];
for (const persona of Object.keys(voices)) {
  lines.push(`  ${persona}: {`);
  const emitted = new Set<string>();
  for (const [group, texts] of Object.entries(groups)) {
    texts.forEach((text, index) => {
      if (emitted.has(text)) return;
      emitted.add(text);
      const path = `./${persona}/${group}/${String(index + 1).padStart(2, "0")}.mp3`;
      lines.push(`    ${JSON.stringify(text)}: require(${JSON.stringify(path)}),`);
    });
  }
  lines.push("  },");
}
lines.push("};", "");
await writeFile(resolve(OUTPUT, "manifest.ts"), lines.join("\n"));
}

void main().catch((error) => {
  console.error(error);
  process.exit(1);
});
